// Writes an app.monzerallan.com-specific .htaccess into dist-app/, replacing
// the generic one Vite already copied from public/.htaccess (shared with the
// marketing build). Kept as a post-build step — rather than a second public/
// directory — specifically so the stricter CSP below only ever applies to
// the Web App property and can never regress the marketing website, which
// keeps using public/.htaccess completely unchanged.
const fs = require("fs");
const path = require("path");

const OUT = path.join(__dirname, "..", "dist-app", ".htaccess");

const CSP = [
  "default-src 'self'",
  "script-src 'self' https://www.youtube.com",
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
  "font-src 'self' https://fonts.gstatic.com",
  "img-src 'self' data: https:",
  "connect-src 'self' https://*.supabase.co wss://*.supabase.co https://www.youtube.com",
  "frame-src https://www.youtube.com https://www.youtube-nocookie.com",
  "media-src 'self' https://*.supabase.co",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'self'",
].join("; ");

const CONTENT = `# Dr. Monzer Allan — Web App (app.monzerallan.com)
# Generated by scripts/write-app-htaccess.cjs — do not hand-edit dist-app/.htaccess,
# edit this script instead and re-run \`npm run build:app\`.

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase /

  # Serve existing files/directories as-is (including sw.js, manifest.webmanifest, icons)
  RewriteCond %{REQUEST_FILENAME} -f [OR]
  RewriteCond %{REQUEST_FILENAME} -d
  RewriteRule ^ - [L]

  # Route everything else through index.html for client-side routing —
  # required so /health, /ai, /consultations, /food-scanner, etc. work on
  # direct load and on refresh, not just via in-app navigation.
  RewriteRule ^ index.html [L]
</IfModule>

# The service worker file itself must never be cached, or visitors could get
# stuck on a stale version. Workbox's precached assets are content-hashed and
# safe to cache long-term.
<IfModule mod_headers.c>
  <FilesMatch "^sw\\.js$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
  <FilesMatch "^manifest\\.webmanifest$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/javascript application/javascript application/json image/svg+xml application/manifest+json
</IfModule>

<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType text/css "access plus 1 year"
  ExpiresByType application/javascript "access plus 1 year"
  ExpiresByType image/png "access plus 1 year"
  ExpiresByType image/jpeg "access plus 1 year"
  ExpiresByType image/webp "access plus 1 year"
  ExpiresByType image/svg+xml "access plus 1 year"
  ExpiresByType text/html "access plus 0 seconds"
</IfModule>

<IfModule mod_headers.c>
  <FilesMatch "\\.(css|js|png|jpg|jpeg|webp|svg|woff2?)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  Header set X-Content-Type-Options "nosniff"
  Header set X-Frame-Options "SAMEORIGIN"
  Header set Referrer-Policy "strict-origin-when-cross-origin"
  Header set Permissions-Policy "geolocation=(self), camera=(self), microphone=()"
  Header set Content-Security-Policy "${CSP}"
</IfModule>
`;

fs.writeFileSync(OUT, CONTENT);
console.log("Wrote", OUT);
