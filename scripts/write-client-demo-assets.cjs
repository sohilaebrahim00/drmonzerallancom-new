// Writes demo.monzerallan.com-specific robots.txt and .htaccess into
// dist-demo/, replacing the generic ones Vite already copied from public/
// (shared with the marketing build). Kept as a post-build step — rather
// than a second public/ directory — specifically so:
//   1. This subdomain is never indexed (Disallow: / + X-Robots-Tag header),
//      while the real public/robots.txt (Allow: / with a real sitemap)
//      stays completely unchanged for monzerallan.com.
//   2. SPA routing works for direct loads/refreshes of /user and /doctor.
// Never touches dist/ or dist-app/ — this script only ever runs as part of
// `npm run build:demo`.
const fs = require("fs");
const path = require("path");

const OUT_DIR = path.join(__dirname, "..", "dist-demo");

if (!fs.existsSync(OUT_DIR)) {
  console.error(`${OUT_DIR} does not exist — run "vite build --mode client-demo" first.`);
  process.exit(1);
}

const ROBOTS_CONTENT = `# This is a private client-preview build — never indexed.
User-agent: *
Disallow: /
`;

const CSP = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
  "font-src 'self' https://fonts.gstatic.com",
  "img-src 'self' data:",
  // Deliberately no connect-src beyond 'self' — this build ships with
  // blank Supabase env vars (see .env.client-demo) and never calls Gemini,
  // so it has nothing legitimate to connect to outside its own origin.
  "connect-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'self'",
].join("; ");

const HTACCESS_CONTENT = `# Dr. Monzer Allan — Client Demo Preview (demo.monzerallan.com)
# Generated by scripts/write-client-demo-assets.cjs — do not hand-edit
# dist-demo/.htaccess, edit this script instead and re-run
# \`npm run build:demo\`.

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase /

  # Serve existing files/directories as-is
  RewriteCond %{REQUEST_FILENAME} -f [OR]
  RewriteCond %{REQUEST_FILENAME} -d
  RewriteRule ^ - [L]

  # Route everything else through index.html for client-side routing —
  # required so /user and /doctor work on direct load and on refresh.
  RewriteRule ^ index.html [L]
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/javascript application/javascript application/json image/svg+xml
</IfModule>

<IfModule mod_headers.c>
  <FilesMatch "\\.(css|js|png|jpg|jpeg|webp|svg|woff2?)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  Header set X-Content-Type-Options "nosniff"
  Header set X-Frame-Options "SAMEORIGIN"
  Header set Referrer-Policy "strict-origin-when-cross-origin"
  Header set Content-Security-Policy "${CSP}"

  # Search-engine protection, independent of and in addition to robots.txt
  # and the <meta name="robots"> tag injected at runtime — this header
  # applies to every response, including ones a crawler that ignores
  # robots.txt or doesn't execute JS would still see.
  Header set X-Robots-Tag "noindex, nofollow"
</IfModule>
`;

fs.writeFileSync(path.join(OUT_DIR, "robots.txt"), ROBOTS_CONTENT);
console.log("Wrote", path.join(OUT_DIR, "robots.txt"));

fs.writeFileSync(path.join(OUT_DIR, ".htaccess"), HTACCESS_CONTENT);
console.log("Wrote", path.join(OUT_DIR, ".htaccess"));
